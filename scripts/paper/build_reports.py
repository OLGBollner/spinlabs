"""Write figures/out/manifest.md and figures/out/numbers.md from the figure records (figures/out/records/*.json)."""

import json

import numpy as np

import config as C

ORDER = ["M1", "M2", "M3", "M4", "S1a", "S1b", "S2", "S3", "S4", "S5", "S6"]


def fmt(v):
    if isinstance(v, float):
        if v == 0 or not np.isfinite(v):
            return str(v)
        return f"{v:.4g}"
    return str(v)


def render(obj, depth=0):
    pad = "  " * depth
    lines = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            if isinstance(v, (dict, list)) and v and not (isinstance(v, list) and all(
                    not isinstance(x, (dict, list)) for x in v) and len(v) <= 25):
                lines.append(f"{pad}- **{k}**:")
                lines += render(v, depth + 1)
            elif isinstance(v, list):
                lines.append(f"{pad}- **{k}**: {', '.join(fmt(x) for x in v)}")
            else:
                lines.append(f"{pad}- **{k}**: {fmt(v)}")
    elif isinstance(obj, list):
        for x in obj:
            if isinstance(x, (dict, list)):
                inner = render(x, depth + 1)
                lines.append(f"{pad}- " + (inner[0].strip()[2:] if inner else ""))
                lines += inner[1:]
            else:
                lines.append(f"{pad}- {fmt(x)}")
    return lines


def production_block():
    T = C.TEMPERATURES
    return [
        "## Production configuration (scripts/paper/config.py)", "",
        f"- sigma: {C.SIGMA:g} meV, all systems",
        f"- direct rate: {C.DIRECT} (J = C E^3, C from the folded acoustic modes, V_0pm)",
        "- two-phonon pairs: zero-gap pairs excluded by symmetry ((l, l) and the Ex-Ey partners of each degenerate "
        "doublet); no energy tolerance (no script passes zero_gap_tol)",
        "- off-diagonal pairs: computed where a package has them (NV 64 AO; VV0 128 AO and UO within |gap| <~ 10-11 "
        "meV), geometric-mean fill otherwise (E x E: sqrt(V_T(i,i) V_T(j,j)); A x E: sqrt(V00(a,a) V_T(e,e)))",
        "- first-order Raman (second_order process): excluded; rates = direct + two-phonon",
        "- steps: NV 64 = 0.1, NV 512 = 0.05, VV0 128 = 0.05, ClV 576 = 0.05 (packages listed per figure)",
        "- second-order couplings via plot_t1_comparison.coupling_manager with exclude_inconsistent_pairs=True "
        "(second-order entries inconsistent with first order are dropped)",
        f"- temperatures: {T[0]:g}-{T[-1]:g} K, step {T[1] - T[0]:g} K",
        "- T1: rate matrix A from the directional rates, p(t) = exp(A t) p0 from the polarized state (exact "
        "eigen-decomposition), a exp(-t/T1) + c fitted to p_init on 10000 points up to t = 10 T1_eig + 1/T "
        "(>= 5 T1_eig at every T, so no grid change was needed); the eigenvalue T1 only as fallback (fit failure or "
        "T1_eig > 1e9 s). 0 K gives no T1 (NaN). Same procedure for the computed curves, the Cambria ab initio curve and the Lin and Cambria data",
        "- V_Si^- excluded everywhere (its D_table row copied unchanged)",
        "- naming: AO = all orbitals (all_bands), UO = unpaired orbitals (defect_band_approx, 3/2 spin correction)",
        "",
    ]


def main():
    recs = {p.stem: json.loads(p.read_text()) for p in sorted(C.RECORDS.glob("*.json"))}
    ids = [i for i in ORDER if i in recs] + [i for i in recs if i not in ORDER]

    man = ["# Paper figures: manifest", "", "Generated by scripts/paper/build_reports.py from figures/out/records/.",
           "Run from the repo root: `bash scripts/paper/run_all.sh`.", ""] + production_block()
    man += ["## T1 eigenvalue fallbacks", ""]
    any_fb = False
    for i in ids:
        for f in recs[i]["fallbacks"]:
            man.append(f"- {i}: {f['curve']} at {f['T_K']:g} K")
            any_fb = True
    if not any_fb:
        man.append("- none")
    man.append("")
    for i in ids:
        r = recs[i]
        man += [f"## {i}: {r['title']}", "", f"- script: `{r['script']}`",
                f"- files: {', '.join('`figures/out/' + f + '`' for f in r['files'])}"]
        man += render(r["settings"])
        man.append("")
    (C.OUT / "manifest.md").write_text("\n".join(man) + "\n")

    num = ["# Paper figures: numbers", "", "Values at grid temperatures (no interpolation); T1 in s, C in 1/meV^2.", ""]
    for i in ids:
        r = recs[i]
        if not r["numbers"]:
            continue
        num += [f"## {i}: {r['title']}", ""] + render(r["numbers"]) + [""]
    num += ["## T1 fit vs eigenvalue: largest relative difference per curve", "",
            "|fit - eig| / eig over the points where the population fit succeeded. A large value is expected where "
            "the initial-state population does not see the slowest decay mode (e.g. m_s = 0 at low T: p_0 decays at "
            "3 Omega while the slowest eigenvalue is ~Omega + 2 gamma).", "",
            "| figure | curve | max rel. diff. | at T (K) | points |", "|---|---|---|---|---|"]
    for i in ids:
        for f in recs[i]["fit_vs_eigen"]:
            extra = f" (sigma {f['at_sigma_meV']:g} meV)" if "at_sigma_meV" in f else ""
            num.append(f"| {i} | {f['curve']} | {f['max_rel_diff']:.3g} | {f['at_T_K']:g}{extra} | {f['n_points']} |")
    (C.OUT / "numbers.md").write_text("\n".join(num) + "\n")
    print("wrote", C.OUT / "manifest.md", "and", C.OUT / "numbers.md")


if __name__ == "__main__":
    main()

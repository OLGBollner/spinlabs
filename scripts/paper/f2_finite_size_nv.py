"""F2: finite-size effects of NV-, T1 (m_s = 0) of NV- (64) and NV- (512) against temperature, AO and UO.

Both cells with the same pair treatment: diagonal + geometric-mean fill, zero-gap pairs excluded (the NV- (512)
production treatment, "diagonal-sqrt" in plot_t1_comparison.coupling_manager). For NV- (64) this is the fill-only
case, not its production all-pairs case. NV- (64) AO with every second-order pair computed (no fill, "computed")
is added as a thin line, so the fill bias and the cell-size effect can be told apart. (b): T1(64) / T1(512),
fill only, AO and UO. Experiment of M2 (m2_nv_t1.experiment) as light gray markers, for orientation only.
The two cells also differ in displacement amplitude: NV- (64) 0.1, not mass-weighted; NV- (512) 0.05,
mass-weighted.
Outputs: figures/out/sm/F2_finite_size_NV.{pdf,png}, figures/out/sm/numbers_finite_size_nv.md, records/F2.json.
"""

import numpy as np

import config as C
from common import Record, directional, rates, t1_details
from m2_nv_t1 import STATE, experiment

T = C.TEMPERATURES
QUOTE = (100.0, 300.0, 500.0)
T_MIN = 50.0  # K, first temperature drawn
CASES = [  # (system, scheme, pairs)
    ("NV_512", "AO", "diagonal-sqrt"), ("NV_512", "UO", "diagonal-sqrt"),
    ("NV_64", "AO", "diagonal-sqrt"), ("NV_64", "UO", "diagonal-sqrt"),
    ("NV_64", "AO", "computed"),
]
STYLE = {"NV_512": "-", "NV_64": "--"}
AMPLITUDE = {"NV_64": "0.1, not mass-weighted", "NV_512": "0.05, mass-weighted"}


def main():
    plt = C.style()
    rec = Record("F2", "NV- finite-size effects: T1 of NV- (64) and NV- (512), same pair treatment",
                 "scripts/paper/f2_finite_size_nv.py", "sm")
    t1 = {}
    for system, scheme, pairs in CASES:
        r = rates(system, scheme, pairs=pairs)
        t, t_eig, src = t1_details(T, directional(r), STATE)
        rec.t1_curve(f"{system} {scheme} {pairs} {STATE}", T, t, t_eig, src)
        t1[(system, scheme, pairs)] = t
    # NV_512 has no off-diagonal pair runs: its production "sqrt" should equal the fill-only treatment used here
    prod512 = {s: t1_details(T, directional(rates("NV_512", s)), STATE)[0] for s in C.SCHEMES}
    ok = T >= T_MIN
    same512 = {s: float(np.max(np.abs(prod512[s][ok] / t1[("NV_512", s, "diagonal-sqrt")][ok] - 1))) for s in C.SCHEMES}
    rec.check_fallbacks()
    exp = experiment()

    fig, (ax, bx) = plt.subplots(2, 1, figsize=(C.SINGLE, 4.6), sharex=True, gridspec_kw={"height_ratios": [2.2, 1]})
    first = True
    for _, _, _, x, y in exp:
        ax.plot(x, y, ls="none", marker="o", ms=2.8, mfc="#d4d3cf", mec="#b8b6b0", mew=0.4, zorder=1,
                label="experiment (as M2)" if first else None)
        first = False
    for system, scheme, pairs in CASES:
        y = t1[(system, scheme, pairs)]
        if pairs == "computed":
            ax.plot(T[ok], y[ok], color=C.COLORS[scheme], lw=0.7, ls="-", zorder=3,
                    label=f"{C.SYSTEMS[system]['label']} {scheme}, all pairs computed")
        else:
            ax.plot(T[ok], y[ok], color=C.COLORS[scheme], ls=STYLE[system], zorder=2,
                    label=f"{C.SYSTEMS[system]['label']} {scheme}")
    ax.set_yscale("log")
    ax.set_xlim(0, 605)
    lo = min(np.nanmin(v[T >= 100]) for v in t1.values())
    ax.set_ylim(lo / 3, 1e3)
    ax.set_ylabel(r"$T_1$ ($m_s=0$) (s)")
    ax.legend(loc="upper right", fontsize=C.FONT - 2.5, handlelength=2.0, labelspacing=0.3)
    C.panel_letter(ax, 0)

    ratio = {}
    for scheme in C.SCHEMES:
        ratio[scheme] = t1[("NV_64", scheme, "diagonal-sqrt")] / t1[("NV_512", scheme, "diagonal-sqrt")]
        bx.plot(T[ok], ratio[scheme][ok], color=C.COLORS[scheme], label=scheme)
    bx.axhline(1.0, color=C.COLORS["ref"], lw=0.6, ls=":")
    bx.set_xlabel("Temperature (K)")
    bx.set_ylabel(r"$T_1(64)\,/\,T_1(512)$")
    bx.legend(loc="best", fontsize=C.FONT - 2)
    C.panel_letter(bx, 1)
    fig.tight_layout()
    rec.data["files"] = C.save(fig, C.SM, "F2_finite_size_NV")
    plt.close(fig)

    # ------------------------------------------------------------------ numbers
    idx = [int(np.flatnonzero(np.isclose(T, t))[0]) for t in QUOTE]
    fill_bias = t1[("NV_64", "AO", "diagonal-sqrt")] / t1[("NV_64", "AO", "computed")]
    hdr = " | ".join(f"{t:g} K" for t in QUOTE)
    L = ["# Finite-size effects, NV- (F2)", "",
         "Generated by scripts/paper/f2_finite_size_nv.py. Production settings (sigma "
         f"{C.SIGMA:g} meV, Debye direct rate, direct + two-phonon, zero-gap pairs excluded), T1 of m_s = 0. Both "
         "cells: diagonal + geometric-mean fill (the NV- (512) production treatment; for NV- (64) the fill-only "
         "case). The cells also differ in displacement amplitude: NV- (64) 0.1, not mass-weighted; NV- (512) 0.05, "
         "mass-weighted.", "",
         "## T1 (s)", "", f"| case | {hdr} |", "|---|" + "---|" * len(QUOTE)]
    for (system, scheme, pairs), v in t1.items():
        label = "all pairs computed" if pairs == "computed" else "fill only"
        L.append(f"| {system} {scheme} {label} | " + " | ".join(f"{v[i]:.4g}" for i in idx) + " |")
    L += ["", "## T1(64) / T1(512), fill only", "", f"| scheme | {hdr} |", "|---|" + "---|" * len(QUOTE)]
    for scheme in C.SCHEMES:
        L.append(f"| {scheme} | " + " | ".join(f"{ratio[scheme][i]:.3f}" for i in idx) + " |")
    L += ["", "## Fill bias, NV- (64) AO: T1(fill only) / T1(all pairs computed)", "", f"| {hdr} |",
          "|" + "---|" * len(QUOTE), "| " + " | ".join(f"{fill_bias[i]:.3f}" for i in idx) + " |", "",
          "## Check: NV- (512) fill only = its production treatment", "",
          "max abs(T1(production) / T1(fill only) - 1), T >= 50 K: "
          + ", ".join(f"{s} {v:.1e}" for s, v in same512.items()), ""]
    path = C.SM / "numbers_finite_size_nv.md"
    path.write_text("\n".join(L) + "\n")
    print("written", path)

    rec.data["settings"] = {
        "packages": {f"{s} {sc}": C.SYSTEMS[s]["packages"][sc] for s, sc, _ in CASES},
        "sigma_meV": C.SIGMA, "direct": C.DIRECT, "processes": list(C.PROCESSES), "initial state": STATE,
        "pairs": "both cells: diagonal + geometric-mean fill, zero-gap pairs excluded (NV- 512 production; NV- 64 "
                 "fill only); thin line: NV- 64 AO, every pair computed, no fill",
        "note": "the two cells also differ in displacement amplitude: NV- (64) 0.1, not mass-weighted; "
                "NV- (512) 0.05, mass-weighted",
        "displacement amplitude": AMPLITUDE,
        "experiment": "the M2 datasets (m2_nv_t1.experiment), light gray, orientation only",
        "NV- 512 production vs fill only, max rel diff": same512,
        "numbers file": "sm/numbers_finite_size_nv.md",
    }
    rec.data["numbers"] = {
        "T1(64)/T1(512) fill only": {s: {f"{t:g} K": float(ratio[s][i]) for t, i in zip(QUOTE, idx)} for s in C.SCHEMES},
        "NV_64 AO T1(fill only)/T1(all pairs)": {f"{t:g} K": float(fill_bias[i]) for t, i in zip(QUOTE, idx)},
        "T1 (s)": {f"{s} {sc} {p}": {f"{t:g} K": float(v[i]) for t, i in zip(QUOTE, idx)} for (s, sc, p), v in t1.items()},
    }
    rec.write()
    print("\n".join(L[-14:]))


if __name__ == "__main__":
    main()

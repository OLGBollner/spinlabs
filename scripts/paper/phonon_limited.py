"""Onset T_c of the phonon-limited regime: figures/out/main/numbers_phonon_limited.md.

Criterion of Cambria et al., PRL 130, 256903 (2023): T_c is the temperature above which the sample-dependent
(temperature-independent) term of a fit is below 10% of the total fitted rate, i.e. the temperature-dependent
terms exceed 9 times the constant.

  NV- (check of the 125 K line of M2 and sq_dq_rates_cambria_measured, which stays at 125 K): Cambria's Eqs. 4-5,
    Omega = A1 n1(n1+1) + A2 n2(n2+1) + A3(S), gamma likewise with B; SM Table S1 (A1, A2, B1, B2, Delta1, Delta2,
    fit to their experiment) and SM Table S2 (A3, B3 per sample).
  V_Si- (M5): Simin et al., PRB 95, 161201(R) (2017), Eq. 2, 1/T1 = A0 + A1 T + A5 T^5 + R / (exp(Delta/kT) - 1),
    their Table I: A0 <= 0.1 1/s (an upper bound only), A1 = 1.0(2) x 10^-2 1/(K s), A5 = 1.1(2) x 10^-9 1/(K^5 s),
    R = 300(150) 1/s, Delta = 25 meV. The temperature-independent term is A0; with A0 at its bound the T_c is an
    upper limit (a smaller A0 gives a lower T_c), so T_c is also given for A0 = 0.05 and 0.01 1/s.
Run from the repo root: python scripts/paper/phonon_limited.py
"""

import numpy as np
import scipy.constants as Cn
from scipy.optimize import brentq

import config as C

KB_MEV = Cn.k / Cn.e * 1e3  # meV/K
FRACTION = 0.10
# Cambria et al. (2023), SM Table S1 (fit to experiment) and Table S2 (sample-dependent constants)
CAMBRIA_S1 = dict(A1=0.58e3, B1=1.51e3, Delta1=68.2, A2=9e3, B2=4.8e3, Delta2=167.0)
CAMBRIA_S2 = {"A": dict(A3=0.013, B3=0.06), "B": dict(A3=0.010, B3=0.30)}
# Simin et al. (2017), Table I (fit of their Fig. 2(c) to Eq. 2)
SIMIN = dict(A0=0.1, A1=1.0e-2, A5=1.1e-9, R=300.0, Delta=25.0)
SIMIN_A0_ALT = (0.05, 0.01)


def onset(dep, const):
    """Lowest T at which const / (const + dep(T)) falls to FRACTION (dep increasing)."""
    return brentq(lambda T: dep(T) - const * (1 - FRACTION) / FRACTION, 0.5, 1000.0)


def cambria_dep(rate):
    p = CAMBRIA_S1
    a1, a2 = (p["A1"], p["A2"]) if rate == "Omega" else (p["B1"], p["B2"])

    def dep(T):
        n1, n2 = 1 / np.expm1(p["Delta1"] / (KB_MEV * T)), 1 / np.expm1(p["Delta2"] / (KB_MEV * T))
        return a1 * n1 * (n1 + 1) + a2 * n2 * (n2 + 1)

    return dep


def simin_dep(T):
    p = SIMIN
    return p["A1"] * T + p["A5"] * T**5 + p["R"] / np.expm1(p["Delta"] / (KB_MEV * T))


def main():
    L = ["# Onset of the phonon-limited regime", "",
         "Generated by scripts/paper/phonon_limited.py. Criterion of Cambria et al., PRL 130, 256903 (2023): T_c is "
         "the temperature above which the sample-dependent (temperature-independent) term of the fit is below 10% "
         "of the total fitted rate.", "",
         "## V_Si- (M5): Simin et al., PRB 95, 161201(R) (2017)", "",
         "Fit: their Eq. 2, 1/T1 = A0 + A1 T + A5 T^5 + R / (exp(Delta/kT) - 1), parameters from their Table I: "
         "A0 <= 0.1 1/s, A1 = 1.0(2) x 10^-2 1/(K s), A5 = 1.1(2) x 10^-9 1/(K^5 s), R = 300(150) 1/s, "
         "Delta = 25 meV (defined in scripts/paper/phonon_limited.py, SIMIN). The temperature-independent term is "
         "A0, given only as an upper bound, so T_c at A0 = 0.1 1/s is an upper limit.", "",
         "| A0 (1/s) | T_c (K) | A1 T at T_c (1/s) | A5 T^5 at T_c | Orbach term at T_c |", "|---|---|---|---|---|"]
    for a0 in (SIMIN["A0"],) + SIMIN_A0_ALT:
        tc = onset(simin_dep, a0)
        orb = SIMIN["R"] / np.expm1(SIMIN["Delta"] / (KB_MEV * tc))
        L.append(f"| {a0:g}{' (bound, used)' if a0 == SIMIN['A0'] else ''} | {tc:.1f} | {SIMIN['A1'] * tc:.3g} | "
                 f"{SIMIN['A5'] * tc**5:.3g} | {orb:.3g} |")
        print(f"Simin A0={a0:g}: T_c = {tc:.2f} K")
    L += ["", "## NV- check (the line stays at 125 K, Cambria's value)", "",
          "Fit: Cambria Eqs. 4-5 with SM Table S1 (A1 = 580, A2 = 9000, B1 = 1510, B2 = 4800 1/s, Delta1 = 68.2, "
          "Delta2 = 167 meV) and Table S2 (A3, B3 per sample).", "",
          "| sample, rate | constant (1/s) | T_c (K) |", "|---|---|---|"]
    for sample in ("A", "B"):
        for rate, key in (("Omega", "A3"), ("gamma", "B3")):
            const = CAMBRIA_S2[sample][key]
            tc = onset(cambria_dep(rate), const)
            L.append(f"| sample {sample}, {rate} | {key} = {const:g} | {tc:.1f} |")
            print(f"Cambria sample {sample} {rate}: T_c = {tc:.2f} K")
    path = C.MAIN / "numbers_phonon_limited.md"
    path.write_text("\n".join(L) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
